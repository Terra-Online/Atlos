// Fixed tile corridors authored from the scene navigation occupancy. These only
// select physical input; the Rust backbone must prove every movement connection.
// Rows encode [z, firstX, lastX], retaining built-empty tiles around the guide.
function corridor(
  min: [number, number],
  max: [number, number],
  rows: [number, number, number][],
): Window {
  return {
    min,
    max,
    tiles: rows.flatMap(([z, first, last]) =>
      Array.from({ length: last - first + 1 }, (_, i) => ({ x: first + i, z })),
    ),
  };
}

