import type { compareQuality, qualityGate } from '#@/bench/quality.ts';
import { isTimedOut, summarizeQuality } from '#@/bench/quality.ts';
import type { runBenchmark } from '#@/bench/run.ts';
import { QUERY_SLO_MS } from '#@/bench/slo.ts';

type Report = Awaited<ReturnType<typeof runBenchmark>>;
export interface MarkdownReport extends Report {
  scene: string;
  revision: string;
  sourceSha256: string;
  node: string;
  concurrency: number;
  execution: { mode: string; workers: number; lanes: number };
  comparison?: ReturnType<typeof compareQuality> & { speedup?: number };
  prototype?: {
    implementation: string;
    sourceSha256: string;
    binarySha256?: string;
    locomotionLabelLimit?: number;
    nativeLocomotion?: boolean;
    nativeCollision?: boolean;
    nativeGroundTrace?: boolean;
    nativeGoals?: boolean;
    nativeCandidate?: boolean;
    nativeRoute?: boolean;
  };
  catalogTraining?: {
    algorithm: 'approximate-static-actions';
    ids: string[];
    wallMs: number;
    completed: number;
    stats: { added: number; scopes: number };
  };
  workingTreeDirty?: boolean;
  qualityGate?: ReturnType<typeof qualityGate>;
}
const number = (value: number | null, digits = 3) =>
  value === null ? 'n/a' : value.toFixed(digits);
const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function benchmarkMarkdown(report: MarkdownReport): string {
  const { batch, comparison } = report;
  const quality = summarizeQuality(batch.results);
  const successfulThroughput =
    batch.successfulQueriesPerSecond ??
    (quality.completed * (batch.rounds ?? 1)) / ((batch.totalWallMs ?? batch.wallMs) / 1000);
  const rows = [
    '> This message is generated by AI.',
    '',
    '<!-- ganglia-benchmark-results -->',
    '',
    `Ganglia benchmark: **${cell(report.scene)}**, ${batch.results.length} queries, ${report.execution.workers || 1} worker(s), ${report.concurrency} lane(s).`,
    '',
    '| Metric | Result |',
    '| --- | ---: |',
    ...(batch.meanSerialQueryMs === undefined
      ? []
      : [`| Mean serial attempt time | ${number(batch.meanSerialQueryMs)} ms/query |`]),
    `| Attempt throughput | ${number(batch.queriesPerSecond, 3)} queries/s |`,
    `| Successful throughput | ${number(successfulThroughput, 3)} complete routes/s |`,
    `| SLO complete routes (≤ ${QUERY_SLO_MS.toLocaleString('en-US')} ms/query) | ${quality.completed}/${batch.results.length} |`,
    `| Timed-out queries | ${quality.timedOut}/${batch.results.length} |`,
  ];
  if (comparison)
    rows.push(
      `| Lost / gained solutions | ${comparison.lostSolutions.length} / ${comparison.gainedSolutions.length} |`,
      `| Recovered timed-out solutions | ${comparison.recoveredTimeouts?.length ?? 0} |`,
      `| Geometric mean / worst cost ratio | ${number(comparison.geometricMeanCostRatio, 6)} / ${number(comparison.worstCostRatio, 6)} |`,
      ...(comparison.speedup === undefined
        ? []
        : [
            `| Speedup vs reference | ${report.qualityGate?.passed === false || comparison.lostSolutions.length || comparison.gainedSolutions.length || quality.completed !== batch.results.length ? 'n/a (quality/SLO gate or solution set changed)' : `${number(comparison.speedup)}×`} |`,
          ]),
    );
  if (report.qualityGate)
    rows.push(
      `| Quality gate | ${report.qualityGate.passed ? 'PASS' : `FAIL: ${cell(report.qualityGate.failures.join('; '))}`} |`,
    );
  rows.push(
    '',
    '<details>',
    '<summary>Measurement details</summary>',
    '',
    `Measured ${batch.rounds ?? 1} complete batch(es) after one prewarm. Input loading, solver preparation and prewarm are excluded. Each query recomputes its route.`,
    '',
    `- Mean batch wall time: ${number(batch.wallMs)} ms; total: ${number(batch.totalWallMs ?? batch.wallMs)} ms.`,
    `- Batch samples (ms): ${(batch.wallSamplesMs ?? [batch.wallMs]).map((sample) => number(sample)).join(', ')}.`,
    `- Excluded prewarm: ${number(report.prewarmMs / 1000)} s.`,
    `- Excluded recovery setup: ${number((batch.recoverySetupMs ?? 0) / 1000)} s.`,
    `- Stable outcomes in every round: ${batch.results.filter((r) => r.sameOutcomeAsPrewarm && r.sameTruncationAsPrewarm).length}/${batch.results.length}.`,
    `- Truncated discovery: ${batch.results.filter((r) => r.truncated).length}/${batch.results.length}.`,
    `- Total modeled travel time: ${number(quality.totalCostSeconds, 6)} s.`,
    `- The per-query SLO excludes queueing and input loading. Timeouts count as failed routes. Successful throughput uses completed routes and the full measured batch wall time.`,
  );
  if (report.catalogTraining) {
    const training = report.catalogTraining;
    rows.push(
      `- Frozen static-action catalog: ${training.stats.added} actions, ${training.stats.scopes} scopes.`,
      `- Excluded training: ${number(training.wallMs / 1000)} s; ${training.ids.length} queries, ${training.completed} complete.`,
    );
  }
  rows.push(
    `- Revision: \`${report.revision.slice(0, 7)}\`${report.workingTreeDirty ? ' (uncommitted changes)' : ''}; Node: \`${report.node}\`.`,
    '',
    '</details>',
    '',
    '<details>',
    '<summary>Per-query route results</summary>',
    '',
    '| Query | Status | Query time (ms) | Modeled cost (s) |',
    '| --- | --- | ---: | ---: |',
    ...batch.results.map(
      (row) =>
        `| ${cell(row.id)} | ${isTimedOut(row) ? 'timeout' : `${cell(row.status)}${row.partial ? ' (partial)' : ''}`} | ${number(row.wallMs ?? null)} | ${number(isTimedOut(row) ? null : row.cost, 6)} |`,
    ),
    '',
    '</details>',
    '',
  );
  return rows.join('\n');
}
